// Extract <img src+alt> and CSS background-image URLs from the 29 Stitch
// code.html exports into a typed TS module. Original remote URLs are kept
// verbatim (provenance); no asset is invented.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const srcDir =
  process.env.STITCH_SRC ||
  "/private/tmp/fasearch-stitch-review-20261013/stitch_fashionsearch_ai_storefront";
const outFile = join(root, "..", "src", "lib", "stitch-assets.ts");

const folders = readdirSync(srcDir, { withFileTypes: true })
  .filter((e) => e.isDirectory() && e.name.startsWith("fashionsearch_ai_"))
  .map((e) => e.name)
  .filter((n) => !["fashionsearch_ai_system_admin"].includes(n))
  .sort();

function decode(s) {
  return s
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">");
}

const screens = [];
for (const folder of folders) {
  let html = "";
  try {
    html = readFileSync(join(srcDir, folder, "code.html"), "utf8");
  } catch {
    continue;
  }
  const images = [];
  const seen = new Set();
  const imgRe = /<img\b[^>]*src="([^"]+)"[^>]*>/gi;
  let m;
  while ((m = imgRe.exec(html)) !== null) {
    const tag = m[0];
    const src = decode(m[1]);
    if (!src.startsWith("http") || seen.has(src)) continue;
    seen.add(src);
    const alt = decode(tag.match(/data-alt="([^"]*)"/)?.[1] ?? tag.match(/alt="([^"]*)"/)?.[1] ?? "");
    images.push({ src, alt: alt.slice(0, 220) });
  }
  const bgRe = /background-image:\s*url\(['"]?(https?:[^'")]+)['"]?\)/gi;
  while ((m = bgRe.exec(html)) !== null) {
    const src = decode(m[1]);
    if (seen.has(src)) continue;
    seen.add(src);
    images.push({ src, alt: "" });
  }
  const title = decode(html.match(/<title>([^<]*)<\/title>/i)?.[1] ?? folder);
  screens.push({ folder, title, images });
}

const total = screens.reduce((n, s) => n + s.images.length, 0);
const lines = [
  "// AUTO-GENERATED by fe/scripts/extract-stitch-assets.mjs — do not hand-edit.",
  "// Provenance: stitch_fashionsearch_ai_storefront (1).zip",
  "// c96fb87281391fe04482247466deda95ee1f21ef083844072bfe1cb85bc43a69",
  `// ${screens.length} screens, ${total} image references.`,
  "",
  "export type StitchImage = { src: string; alt: string };",
  "export type StitchScreen = { folder: string; title: string; images: StitchImage[] };",
  "",
  `export const STITCH_SCREENS: StitchScreen[] = ${JSON.stringify(screens)};`,
  "",
  "const byFolder = new Map(STITCH_SCREENS.map((s) => [s.folder, s]));",
  "",
  "export function stitchImages(folder: string): StitchImage[] {",
  "  return byFolder.get(folder)?.images ?? [];",
  "}",
  "",
  "export function stitchImage(folder: string, index: number): StitchImage | undefined {",
  "  return stitchImages(folder)[index];",
  "}",
  "",
];
mkdirSync(join(root, "..", "src", "lib"), { recursive: true });
writeFileSync(outFile, lines.join("\n"));
console.log(`wrote ${outFile}: ${screens.length} screens, ${total} images`);
