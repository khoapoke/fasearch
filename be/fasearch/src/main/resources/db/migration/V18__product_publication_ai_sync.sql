ALTER TABLE san_pham ADD COLUMN IF NOT EXISTS publication_status VARCHAR(20) NOT NULL DEFAULT 'PUBLISHED';
ALTER TABLE san_pham ADD COLUMN IF NOT EXISTS publication_version BIGINT NOT NULL DEFAULT 1;
ALTER TABLE san_pham ADD COLUMN IF NOT EXISTS published_ref_id BIGINT REFERENCES san_pham(ma_sp);
CREATE INDEX IF NOT EXISTS idx_san_pham_publication_status ON san_pham(publication_status);
CREATE INDEX IF NOT EXISTS idx_san_pham_published_ref ON san_pham(published_ref_id);

CREATE TABLE IF NOT EXISTS product_draft (
    ma_ban_nhap BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_sp BIGINT REFERENCES san_pham(ma_sp),
    ten_sp VARCHAR(255),
    ma_danh_muc BIGINT REFERENCES danh_muc(ma_danh_muc),
    ma_thuong_hieu BIGINT REFERENCES thuong_hieu(ma_thuong_hieu),
    model_code VARCHAR(100),
    chat_lieu VARCHAR(100),
    kieu_dang VARCHAR(100),
    mo_ta TEXT,
    gia_ban NUMERIC(15,2),
    hinh_anh_sp VARCHAR(255),
    trang_thai VARCHAR(50),
    phien_ban BIGINT NOT NULL DEFAULT 1,
    trang_thai_ban_nhap VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    nguon_url TEXT,
    nguon_hash VARCHAR(64),
    nguon_loai VARCHAR(30),
    ngay_tao TIMESTAMP NOT NULL DEFAULT NOW(),
    ngay_cap_nhat TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_product_draft_open_per_product ON product_draft(ma_sp) WHERE ma_sp IS NOT NULL AND trang_thai_ban_nhap = 'DRAFT';

CREATE TABLE IF NOT EXISTS product_draft_variant (
    ma_ban_nhap_chi_tiet BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_ban_nhap BIGINT NOT NULL REFERENCES product_draft(ma_ban_nhap) ON DELETE CASCADE,
    so_luong INTEGER,
    mau_sac VARCHAR(50),
    kich_co VARCHAR(50),
    ma_vach VARCHAR(100),
    gia_phu_thu NUMERIC(15,2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS product_ai_sync (
    ma_sp BIGINT PRIMARY KEY REFERENCES san_pham(ma_sp) ON DELETE CASCADE,
    phien_ban BIGINT NOT NULL,
    trang_thai VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    so_lan_thu INTEGER NOT NULL DEFAULT 0,
    lan_cap_nhat_cuoi TIMESTAMP NOT NULL DEFAULT NOW(),
    loi_cuoi TEXT
);
