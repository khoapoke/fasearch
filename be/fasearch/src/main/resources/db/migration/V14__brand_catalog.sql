CREATE TABLE IF NOT EXISTS thuong_hieu (
    ma_thuong_hieu BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_thuong_hieu VARCHAR(150) NOT NULL,
    slug VARCHAR(100) NOT NULL UNIQUE,
    quoc_gia VARCHAR(100),
    logo_file_name VARCHAR(255),
    official_url TEXT,
    provenance_url TEXT,
    provenance_sha256 VARCHAR(64),
    da_xoa BOOLEAN NOT NULL DEFAULT FALSE,
    ngay_tao TIMESTAMP NOT NULL DEFAULT NOW()
);

ALTER TABLE san_pham ADD COLUMN IF NOT EXISTS ma_thuong_hieu BIGINT;
ALTER TABLE san_pham ADD COLUMN IF NOT EXISTS model_code VARCHAR(100);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_san_pham_thuong_hieu') THEN
        ALTER TABLE san_pham ADD CONSTRAINT fk_san_pham_thuong_hieu
            FOREIGN KEY (ma_thuong_hieu) REFERENCES thuong_hieu(ma_thuong_hieu);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_san_pham_thuong_hieu ON san_pham(ma_thuong_hieu);
CREATE UNIQUE INDEX IF NOT EXISTS uq_san_pham_brand_model ON san_pham(ma_thuong_hieu, model_code);
