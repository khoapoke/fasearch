CREATE TABLE IF NOT EXISTS payment_attempt (
    ma_payment_attempt BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_don_hang BIGINT NOT NULL REFERENCES don_hang(ma_don_hang),
    provider VARCHAR(30) NOT NULL,
    provider_session_id VARCHAR(255),
    provider_reference VARCHAR(255),
    amount NUMERIC(15,2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(30) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    expires_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_payment_attempt_provider_key UNIQUE (provider, idempotency_key)
);

CREATE INDEX IF NOT EXISTS idx_payment_attempt_order ON payment_attempt(ma_don_hang);
CREATE INDEX IF NOT EXISTS idx_payment_attempt_reference ON payment_attempt(provider, provider_reference);

CREATE TABLE IF NOT EXISTS payment_event (
    ma_payment_event BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(30) NOT NULL,
    provider_event_id VARCHAR(255) NOT NULL,
    ma_payment_attempt BIGINT REFERENCES payment_attempt(ma_payment_attempt),
    ma_don_hang BIGINT REFERENCES don_hang(ma_don_hang),
    payload_sha256 VARCHAR(64) NOT NULL,
    status VARCHAR(30) NOT NULL,
    received_at TIMESTAMP NOT NULL DEFAULT NOW(),
    processed_at TIMESTAMP,
    error_code VARCHAR(100),
    CONSTRAINT uq_payment_event_provider_event UNIQUE (provider, provider_event_id)
);

CREATE INDEX IF NOT EXISTS idx_payment_event_attempt ON payment_event(ma_payment_attempt);
